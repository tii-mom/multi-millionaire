function interpolate(template: string, values?: Record<string, string | number | null | undefined>) {
  if (!values) return template;
  return template.replace(/\{(\w+)\}/g, (_, key) => String(values[key] ?? ""));
}

function getInitialLanguage(): Language {
  if (typeof window === "undefined") return "en";
  const stored = window.localStorage.getItem("72h_language");
  if (stored === "en" || stored === "zh") return stored;
  return window.navigator.language.toLowerCase().startsWith("zh") ? "zh" : "en";
}

function normalizeErrorMessage(message: string, t: Translate) {
  if (/Failed to fetch|NetworkError/i.test(message)) return t("error.network");
  const requestMatch = message.match(/Request failed with (\d+)/i);
  if (requestMatch) return t("error.requestFailed", { status: requestMatch[1] });
  return message || t("error.unknown");
}

export type Translate = (key: string, values?: Record<string, string | number | null | undefined>) => string;

type I18nContextValue = {
  language: Language;
  locale: string;
  setLanguage: (language: Language) => void;
  toggleLanguage: () => void;
  t: Translate;
  formatError: (error: unknown, fallbackKey: string) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(getInitialLanguage);
  const locale = language === "zh" ? "zh-CN" : "en-US";

  const t = useMemo<Translate>(() => {
    return (key, values) => {
      const template = dictionaries[language][key] ?? dictionaries.en[key] ?? key;
      return interpolate(template, values);
    };
  }, [language]);

  const setLanguage = (nextLanguage: Language) => {
    setLanguageState(nextLanguage);
    window.localStorage.setItem("72h_language", nextLanguage);
  };

  useEffect(() => {
    document.documentElement.lang = language === "zh" ? "zh-CN" : "en";
    document.title = t("app.title");
  }, [language, t]);

  const value = useMemo<I18nContextValue>(() => ({
    language,
    locale,
    setLanguage,
    toggleLanguage: () => setLanguage(language === "zh" ? "en" : "zh"),
    t,
    formatError: (error, fallbackKey) => {
      const fallback = t(fallbackKey);
      const raw = error instanceof Error ? error.message : fallback;
      return normalizeErrorMessage(raw, t);
    },
  }), [language, locale, t]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const value = useContext(I18nContext);
  if (!value) {
    throw new Error("useI18n must be used inside LanguageProvider.");
  }
  return value;
}

export function formatNumber(value: number | string, locale: string, options?: Intl.NumberFormatOptions) {
  return Number(value || 0).toLocaleString(locale, options);
}
